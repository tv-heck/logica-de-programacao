# Atividade 1 - Sum e Max
valores = [10, 20, 30, 40]
soma = sum(valores)
maximo = max(valores)
print("Soma:", soma)
print("Máximo:", maximo)

# Atividade 2 - Comportamento de Listas 
c = 0
s = 0
for x in [5, 10, 15]:
      c = c + 1
      s = s + x
print("Contagem:", c)
print("Soma:", s)

# Atividade 3 - Desafio: Média de uma lista sem laço for
numeros = [30, 40, 70, 100, 150]
media = sum(numeros) / len(numeros)
print("Média:", media)